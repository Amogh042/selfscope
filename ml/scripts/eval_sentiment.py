"""Evaluate the WhatsApp sentiment scorer (web/src/python/enrich/sentiment.py) against the
demo answer key (ml/data/demo_whatsapp_truth.csv). Writes ml/reports/sentiment_report.md
and ml/reports/sentiment_confusion.png.

The scorer is a fixed lexicon + rules (no training), so the whole demo is a test set.

Usage:  python ml/scripts/eval_sentiment.py
"""

from __future__ import annotations

import json
import os
import sys
from collections import Counter

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path[:0] = [os.path.join(ROOT, "web", "src", "python")]

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score  # noqa: E402

from enrich.sentiment import Scorer  # noqa: E402
from parsers.whatsapp import chat_name_from_filename, parse_whatsapp, read_export  # noqa: E402

LABELS = ["neg", "neu", "pos"]
REPORTS = os.path.join(ROOT, "ml", "reports")


def load():
    truth = pd.read_csv(os.path.join(ROOT, "ml", "data", "demo_whatsapp_truth.csv"))
    wa_dir = os.path.join(ROOT, "data", "samples", "whatsapp")
    texts = []
    for name in sorted(os.listdir(wa_dir)):
        with open(os.path.join(wa_dir, name), "rb") as f:
            chat = chat_name_from_filename(name)
            df = parse_whatsapp(read_export(f.read(), name), chat_name=chat)
        kinds = df["meta"].map(lambda m: json.loads(m).get("kind"))
        m = df[(df["event_type"] == "message") & (kinds == "text")]
        t = truth[truth["chat"] == chat]
        assert len(t) == len(m), (chat, len(t), len(m))
        assert (t["text"].str.strip().to_numpy() == m["text"].str.strip().to_numpy()).all(), chat
        texts.append(pd.DataFrame({"chat": chat, "sender": m["actor"].to_numpy(), "text": m["text"].to_numpy(),
                                   "truth": t["label"].to_numpy()}))
    return pd.concat(texts, ignore_index=True)


def main():
    with open(os.path.join(ROOT, "web", "public", "data", "sentiment_lexicon.json"), encoding="utf-8") as f:
        scorer = Scorer(json.load(f))
    df = load()
    scored = df["text"].map(scorer.score)
    df["score"] = scored.map(lambda x: x[0])
    df["pred"] = scored.map(lambda x: x[1])

    def metrics(d):
        return {"n": int(len(d)), "accuracy": round(float(accuracy_score(d.truth, d.pred)), 4),
                "macro_f1": round(float(f1_score(d.truth, d.pred, labels=LABELS, average="macro")), 4)}

    allm, mine = metrics(df), metrics(df[df.sender == "Amogh"])
    uniq = df.drop_duplicates("text")
    um = metrics(uniq)
    base = {"accuracy": round(float((df.truth == "neu").mean()), 4),
            "macro_f1": round(float(f1_score(df.truth, ["neu"] * len(df), labels=LABELS, average="macro")), 4)}
    rep = classification_report(df.truth, df.pred, labels=LABELS, output_dict=True, zero_division=0)
    cm = confusion_matrix(df.truth, df.pred, labels=LABELS)

    os.makedirs(REPORTS, exist_ok=True)
    fig, ax = plt.subplots(figsize=(4.2, 3.6), dpi=130)
    cmn = cm / cm.sum(1, keepdims=True)
    ax.imshow(cmn, cmap="Oranges", vmin=0, vmax=1)
    ax.set_xticks(range(3), LABELS)
    ax.set_yticks(range(3), LABELS)
    for i in range(3):
        for j in range(3):
            ax.text(j, i, f"{cm[i, j]:,}", ha="center", va="center", fontsize=8,
                    color="white" if cmn[i, j] > 0.6 else "black")
    ax.set_xlabel("predicted")
    ax.set_ylabel("true")
    ax.set_title("Sentiment confusion matrix (demo)")
    fig.tight_layout()
    fig.savefig(os.path.join(REPORTS, "sentiment_confusion.png"))
    plt.close(fig)

    # most frequent wrong messages, with what the scorer matched
    wrong = uniq[uniq.truth != uniq.pred].copy()
    wrong["count"] = wrong["text"].map(df["text"].value_counts())
    wrong = wrong.sort_values("count", ascending=False).head(12)
    rows = []
    for r in wrong.itertuples():
        _, _, found = scorer.explain(r.text)
        rows.append(f"| {r.text.replace(chr(10), ' / ')} | {r.truth} | {r.pred} | {r.score:+.2f} | "
                    f"{', '.join(f'{w} {v:+.1f}' for w, v in found) or '(nothing matched)'} | {r.count} |")

    lines = [
        "# WhatsApp sentiment scorer — evaluation",
        "",
        "Scorer: `web/src/python/enrich/sentiment.py` — VADER-style rules over VADER's English lexicon plus a "
        "hand-curated Hinglish lexicon and emojis (`web/public/data/sentiment_lexicon.json`). No training, so the "
        "whole demo is a test set. Generated by `ml/scripts/eval_sentiment.py`.",
        "",
        "Test set: every text message of the 5 demo chats with its true label from `ml/data/demo_whatsapp_truth.csv` "
        "(the label of the positive / neutral / negative pool the demo generator drew the message from).",
        "",
        "## Results",
        "",
        "| Messages | n | Accuracy | Macro-F1 |",
        "|---|---|---|---|",
        f"| All text messages | {allm['n']:,} | {allm['accuracy']:.3f} | {allm['macro_f1']:.3f} |",
        f"| Only the user's own (Amogh) — used for the user's mood | {mine['n']:,} | {mine['accuracy']:.3f} | {mine['macro_f1']:.3f} |",
        f"| Distinct texts (each wording once) | {um['n']:,} | {um['accuracy']:.3f} | {um['macro_f1']:.3f} |",
        f"| Baseline: always 'neutral' | {allm['n']:,} | {base['accuracy']:.3f} | {base['macro_f1']:.3f} |",
        "",
        "| Label | Precision | Recall | F1 | Support |",
        "|---|---|---|---|---|",
        *[f"| {k} | {rep[k]['precision']:.2f} | {rep[k]['recall']:.2f} | {rep[k]['f1-score']:.2f} | {int(rep[k]['support']):,} |"
          for k in LABELS],
        "",
        "![confusion matrix](sentiment_confusion.png)",
        "",
        "## Most frequent mistakes (with what the scorer matched)",
        "",
        "| Message | True | Predicted | Score | Matched words (valence) | Times in demo |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "## Caveats (read before quoting the numbers)",
        "",
        "- **Optimistic:** the demo messages come from a few hundred fixed phrases, and the same person wrote "
        "the demo generator and the Hinglish lexicon. Real chats are far more varied (spelling, slang, sarcasm, "
        "code-mixing), so expect lower accuracy on real data.",
        "- **Lexicon limits:** words outside the lexicons count as neutral; sarcasm and context are invisible; "
        "Gen-Z usage like \"dead 💀\" (= very funny) reads as negative because VADER scores *dead* at -3.3.",
        "- The lexicon was written before this evaluation was run and was **not tuned on its results**.",
        "",
        "Re-run: `python ml/scripts/eval_sentiment.py`",
    ]
    with open(os.path.join(REPORTS, "sentiment_report.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(REPORTS, "sentiment_results.json"), "w", encoding="utf-8") as f:
        json.dump({"all": allm, "mine": mine, "unique": um, "baseline_neutral": base,
                   "per_label": {k: {m: round(rep[k][m], 4) for m in ("precision", "recall", "f1-score")} for k in LABELS},
                   "confusion": cm.tolist(), "labels": LABELS, "pred_counts": dict(Counter(df.pred))}, f, indent=2)
    print(json.dumps({"all": allm, "mine": mine, "unique": um, "baseline": base}, indent=1))


if __name__ == "__main__":
    main()
